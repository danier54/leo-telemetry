"""Shared protocol constants for telemetry decoding."""

# Bell 202 AFSK1200 modulation used to carry AX.25 over audio.
AFSK1200_BAUD_RATE = 1200
AFSK1200_MARK_FREQUENCY_HZ = 1200
AFSK1200_SPACE_FREQUENCY_HZ = 2200

# AX.25 uses HDLC framing and transmits each octet least-significant bit first.
AX25_FLAG_BYTE = 0x7E
AX25_FLAG_BITS = f"{AX25_FLAG_BYTE:08b}"
AX25_ADDRESS_FIELD_BYTES = 7
AX25_MIN_ADDRESS_FIELDS = 2
AX25_CONTROL_FIELD_BYTES = 1
AX25_PID_FIELD_BYTES = 1
AX25_FCS_BYTES = 2
AX25_EXTENSION_BIT = 0x01
AX25_MIN_FRAME_BYTES = (
    AX25_MIN_ADDRESS_FIELDS * AX25_ADDRESS_FIELD_BYTES
    + AX25_CONTROL_FIELD_BYTES
)
